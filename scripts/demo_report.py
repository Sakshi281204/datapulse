"""Run the pipeline on sample data in a temp DB and write a reconciliation report."""
import tempfile
from contextlib import closing
from pathlib import Path

from datapulse.database import get_connection, initialize_database, seed_datasets
from datapulse.pipeline import run_dataset_pipeline


def main():
    root = Path(__file__).resolve().parents[1]
    out = root / "reports" / "sample_run_report.md"
    out.parent.mkdir(exist_ok=True)
    rows = []
    with tempfile.TemporaryDirectory(ignore_cleanup_errors=True) as tmp:
        db = Path(tmp) / "demo.db"
        initialize_database(db)
        seed_datasets(db)
        plan = [
            ("customers", "first run"),
            ("orders", "first run"),
            ("customers", "rerun of same file"),
        ]
        for name, label in plan:
            src = root / "data" / "sample" / (name + ".csv")
            r = run_dataset_pipeline(
                dataset_name=name, source_path=str(src), database_path=db
            )
            pub = r.get("publishing") or {}
            rows.append((
                name, label, r.get("status"), r.get("records_received"),
                pub.get("inserted_count"), pub.get("skipped_count"),
                r.get("records_rejected"), r.get("error_message", ""),
            ))
        with closing(get_connection(db)) as c:
            cust = c.execute("SELECT COUNT(*) FROM customer_target").fetchone()[0]
            orde = c.execute("SELECT COUNT(*) FROM orders_target").fetchone()[0]
            quar = c.execute("SELECT COUNT(*) FROM quarantine_records").fetchone()[0]
            runs = c.execute("SELECT COUNT(*) FROM pipeline_runs").fetchone()[0]
            fk = len(c.execute("PRAGMA foreign_key_check").fetchall())
            integ = c.execute("PRAGMA integrity_check").fetchone()[0]
    L = ["# Sample Run Report", "",
         "Generated by `python scripts/demo_report.py` on a temporary database.", "",
         "| dataset | attempt | status | received | inserted | skipped | rejected | error |",
         "|---|---|---|---|---|---|---|---|"]
    for r in rows:
        L.append("| " + " | ".join(str(x) for x in r) + " |")
    L += ["", "## Reconciliation", "",
          "Per run: received = inserted + skipped + rejected.", ""]
    for r in rows:
        if r[3] is not None and r[4] is not None:
            ok = r[3] == (r[4] or 0) + (r[5] or 0) + (r[6] or 0)
            L.append("- " + r[0] + " (" + r[1] + "): " + ("OK" if ok else "MISMATCH"))
    L += ["", "## Final database state", "",
          "- customer_target rows: " + str(cust),
          "- orders_target rows: " + str(orde),
          "- quarantine_records rows: " + str(quar),
          "- pipeline_runs rows (history kept): " + str(runs),
          "- foreign key violations: " + str(fk),
          "- sqlite integrity_check: " + str(integ), ""]
    text = "\n".join(L)
    out.write_text(text, encoding="utf-8", newline="\n")
    print(text)


if __name__ == "__main__":
    main()